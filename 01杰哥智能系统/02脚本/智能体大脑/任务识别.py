"""
名称：任务识别.py
作用：根据用户输入识别任务类型、复杂度和工具需求。
触发方式：由 v3 智能体大脑服务入口导入调用。
依赖：Python 标准库。
所属系统：01杰哥智能系统
创建/修改记录：2026-04-26 创建第一阶段最小可运行版本。
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any


@dataclass(frozen=True)
class 任务规则:
    类型: str
    关键词: tuple[str, ...]
    默认复杂度: str
    需要工具: bool


规则集: tuple[任务规则, ...] = (
    任务规则("股票研究", ("股票", "股价", "财报", "研报", "估值", "涨跌", "板块", "指数", "港股", "美股", "A股"), "高", True),
    任务规则("视频制作", ("视频", "剪辑", "脚本", "分镜", "字幕", "配音", "封面", "镜头", "素材"), "中", True),
    任务规则("本职工作", ("公文", "汇报", "材料", "方案", "通知", "总结", "会议", "纪要", "台账", "表格"), "中", True),
    任务规则("知识库问答", ("知识库", "资料", "文档", "制度", "依据", "检索", "查一下", "在哪个文件"), "中", True),
    任务规则("代码开发", ("代码", "脚本", "接口", "bug", "报错", "测试", "docker", "容器", "api", "python"), "高", True),
    任务规则("自动化办公", ("自动化", "批量", "定时", "流程", "工作流", "n8n", "企微", "企业微信"), "中", True),
    任务规则("系统运维", ("服务", "端口", "日志", "备份", "恢复", "健康", "状态", "监控", "部署"), "中", True),
)


复杂度分数 = {"低": 1, "中": 2, "高": 3}


def _系统根目录() -> Path:
    return Path(__file__).resolve().parents[3]


def _读取规则配置() -> dict[str, Any]:
    配置路径 = _系统根目录() / "01杰哥智能系统" / "01配置" / "智能体大脑规则.json"
    try:
        return json.loads(配置路径.read_text(encoding="utf-8"))
    except Exception:
        return {}


def 读取任务规则() -> tuple[任务规则, ...]:
    配置规则 = _读取规则配置().get("任务识别规则", [])
    结果: list[任务规则] = []
    for 项 in 配置规则:
        try:
            结果.append(
                任务规则(
                    项["任务类型"],
                    tuple(项.get("关键词", [])),
                    项.get("默认复杂度", "中"),
                    bool(项.get("需要工具", True)),
                )
            )
        except Exception:
            continue
    return tuple(结果) if 结果 else 规则集


def _标准化文本(文本: str | None) -> str:
    return (文本 or "").strip().lower()


def _根据长度修正复杂度(文本: str, 当前复杂度: str) -> str:
    if len(文本) >= 500:
        return "高"
    if len(文本) >= 160 and 复杂度分数[当前复杂度] < 2:
        return "中"
    return 当前复杂度


def 识别任务(文本: str | None, 元数据: dict[str, Any] | None = None) -> dict[str, Any]:
    内容 = _标准化文本(文本)
    元数据 = 元数据 or {}

    if not 内容:
        return {
            "任务类型": "空输入",
            "复杂度": "低",
            "置信度": 1.0,
            "命中关键词": [],
            "需要工具": False,
            "风险等级": "低",
        }

    候选: list[tuple[任务规则, list[str]]] = []
    for 规则 in 读取任务规则():
        命中 = [关键词 for 关键词 in 规则.关键词 if 关键词.lower() in 内容]
        if 命中:
            候选.append((规则, 命中))

    if 候选:
        规则, 命中 = max(候选, key=lambda 项: (len(项[1]), 复杂度分数[项[0].默认复杂度]))
        复杂度 = _根据长度修正复杂度(内容, 规则.默认复杂度)
        置信度 = min(0.95, 0.55 + 0.12 * len(命中))
        需要工具 = 规则.需要工具
        任务类型 = 规则.类型
    else:
        命中 = []
        复杂度 = _根据长度修正复杂度(内容, "低")
        置信度 = 0.45
        需要工具 = False
        任务类型 = "普通对话"

    风险等级 = "低"
    if any(词 in 内容 for 词 in ("删除", "覆盖", "重装", "清空", "迁移生产", "停止生产")):
        风险等级 = "高"
    elif any(词 in 内容 for 词 in ("修改", "安装", "启动", "部署", "拉取模型")):
        风险等级 = "中"

    return {
        "任务类型": 任务类型,
        "复杂度": 复杂度,
        "置信度": round(置信度, 2),
        "命中关键词": 命中,
        "需要工具": 需要工具,
        "风险等级": 风险等级,
        "来源": 元数据.get("来源", "本地接口"),
    }
