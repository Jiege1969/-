"""
名称：能力注册.py
作用：读取 v3 能力注册表，并按任务识别结果输出工具或系统路由计划。
触发方式：由 v3 智能体大脑服务入口导入调用。
依赖：Python 标准库。
所属系统：01杰哥智能系统
安全边界：只读取 v3 配置并生成计划，不执行外部工具、不调用生产服务。
创建/修改记录：2026-04-26 创建第一阶段能力注册模块。
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def _系统根目录() -> Path:
    return Path(__file__).resolve().parents[3]


def 读取能力注册表() -> dict[str, Any]:
    配置路径 = _系统根目录() / "01杰哥智能系统" / "01配置" / "能力注册表.json"
    try:
        数据 = json.loads(配置路径.read_text(encoding="utf-8"))
        数据["配置来源"] = str(配置路径)
        return 数据
    except Exception as 异常:
        return {
            "说明": "内置兜底能力注册表",
            "配置来源": "内置默认",
            "配置读取错误": str(异常),
            "能力": [
                {
                    "能力名": "普通对话",
                    "归属系统": "01杰哥智能系统",
                    "入口类型": "本地大模型",
                    "默认执行方式": "同步",
                    "需要工具": False,
                    "风险等级": "低",
                    "说明": "兜底普通问答。",
                }
            ],
        }


def 能力列表() -> list[dict[str, Any]]:
    return list(读取能力注册表().get("能力", []))


def 规划能力调用(任务识别结果: dict[str, Any] | None = None) -> dict[str, Any]:
    任务识别结果 = 任务识别结果 or {}
    任务类型 = 任务识别结果.get("任务类型", "普通对话")
    风险等级 = 任务识别结果.get("风险等级", "低")
    能力 = next((项 for 项 in 能力列表() if 项.get("能力名") == 任务类型), None)
    if 能力 is None:
        能力 = next((项 for 项 in 能力列表() if 项.get("能力名") == "普通对话"), {})

    需要人工确认 = 风险等级 == "高" or 能力.get("风险等级") == "高"
    return {
        "任务类型": 任务类型,
        "能力名": 能力.get("能力名", "普通对话"),
        "归属系统": 能力.get("归属系统", "01杰哥智能系统"),
        "入口类型": 能力.get("入口类型", "本地大模型"),
        "默认执行方式": 能力.get("默认执行方式", "同步"),
        "需要工具": bool(能力.get("需要工具", False)),
        "能力风险等级": 能力.get("风险等级", "低"),
        "任务风险等级": 风险等级,
        "需要人工确认": 需要人工确认,
        "当前动作": "仅生成计划，不执行外部工具",
        "说明": 能力.get("说明", ""),
    }
