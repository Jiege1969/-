def load_json(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8-sig"))


def write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")


def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def build_markdown(plan: dict[str, Any]) -> str:
    lines = [
        "# 微信短文生成器 v2.1 正式接入方案",
        "",
        f"- 生成时间：{plan['生成时间']}",
        f"- 当前结论：{plan['当前结论']}",
        "",
        "## 接入原则",
        "",
    ]
    for item in plan["接入原则"]:
        lines.append(f"- {item}")
    lines.extend(["", "## 字段映射", ""])
    for row in plan["字段映射"]:
        lines.append(f"- {row['目标字段']}：来源 `{row['来源']}`；要求：{row['要求']}")
    lines.extend(["", "## 分阶段接入步骤", ""])
    for step in plan["分阶段接入步骤"]:
        lines.append(f"{step['阶段']}. {step['名称']}：{step['动作']}；验收：{step['验收']}")
    lines.extend(["", "## 回滚点", ""])
    for item in plan["回滚点"]:
        lines.append(f"- {item}")
    lines.extend(["", "## 禁止动作", ""])
    for item in plan["禁止动作"]:
        lines.append(f"- {item}")
    lines.extend(["", "## 下一步", "", plan["下一步"]])
    return "\n".join(lines) + "\n"


