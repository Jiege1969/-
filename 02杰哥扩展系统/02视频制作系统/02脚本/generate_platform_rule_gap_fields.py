# -*- coding: utf-8 -*-
"""生成平台规则字段待补清单。

安全边界：本脚本只列待补字段，不抓取平台页面，不声明规则为最新正式版本。
真实规则核验必须由人工或总管批准的只读来源核对流程完成。
"""

from __future__ import annotations

from agent_shadow_common import write_artifact


def build() -> dict:
    platforms = ["小红书", "抖音", "视频号", "B站"]
    common_fields = [
        "内容类型允许范围",
        "AI生成内容标识入口",
        "视频时长限制",
        "画幅与分辨率建议",
        "封面与标题限制",
        "标签数量与敏感词限制",
        "素材授权要求",
        "音乐和音效版权要求",
        "低质或同质化内容提示",
        "违规申诉或撤回入口",
    ]
    return {
        "清单定位": {
            "用途": "列出发布前需要人工或只读来源核验的平台规则字段",
            "当前阶段": "待补字段清单",
            "是否最新规则": "否，仅为核验框架",
        },
        "平台字段": [
            {
                "平台": platform,
                "待补字段": common_fields,
                "状态": "待人工核验",
                "不得推导": "不得凭本清单直接放行发布",
            }
            for platform in platforms
        ],
        "跨平台共性门禁": [
            "AI生成内容标识必须逐平台确认。",
            "素材授权必须逐素材确认。",
            "标题、封面、标签不得使用焦虑诱导或绝对化表述。",
            "成语故事和经典语录必须有原创解读，不得仅复述或洗稿。",
        ],
        "红线登记": [
            "不抓取平台页面。",
            "不登录平台账号。",
            "不修改发布适配器为真实发布。",
            "不把待补清单说成正式平台规则。",
        ],
    }


def main() -> int:
    write_artifact("平台规则字段待补清单", "平台规则字段待补清单", build())
    print("平台规则字段待补清单已生成")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
