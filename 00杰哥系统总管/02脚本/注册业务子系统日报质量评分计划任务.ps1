$registered = @()
foreach ($item in $tasks) {
    if (-not (Test-Path -LiteralPath $item.Script)) {
        throw "missing quality script: $($item.Script)"
    }
    $workingDirectory = Split-Path -Parent $item.Script
    if (-not (Test-Path -LiteralPath $pythonExe)) {
        throw "missing python executable: $pythonExe"
    }
    $action = New-ScheduledTaskAction -Execute $pythonExe -Argument "`"$($item.Script)`"" -WorkingDirectory $workingDirectory
    $trigger = New-ScheduledTaskTrigger -Daily -At $item.At
    $settings = New-ScheduledTaskSettingsSet `
        -MultipleInstances IgnoreNew `
        -AllowStartIfOnBatteries `
        -DontStopIfGoingOnBatteries `
        -StartWhenAvailable `
        -Hidden `
        -ExecutionTimeLimit (New-TimeSpan -Minutes 10)
    $principal = New-ScheduledTaskPrincipal -UserId $env:USERNAME -LogonType Interactive -RunLevel Limited
    $task = New-ScheduledTask -Action $action -Trigger $trigger -Settings $settings -Principal $principal
    Register-ScheduledTask -TaskName $item.Name -InputObject $task -Force | Out-Null
    $registered += [ordered]@{
        task_name = $item.Name
        schedule = "daily $($item.At)"
        script = $item.Script
    }
}

